#!/usr/bin/env python3
"""Writes app/src/main/assets/pinyin.txt: the most common tonal pinyin of each of the 6,763
GB2312 hanzi, one "字<TAB>pīn" per line. VoiceService uses it to turn a custom wake word typed
in Chinese into the wake-word model's tokens.

Data: pypinyin (MIT, https://github.com/mozillazg/python-pinyin), built on pinyin-data (MIT).

Usage (from the repo root): uvx --with pypinyin python scripts/make-pinyin-table.py
"""
from pathlib import Path

from pypinyin import Style, pinyin

OUT = Path(__file__).resolve().parent.parent / "app/src/main/assets/pinyin.txt"


def gb2312_hanzi():
    for hi in range(0xB0, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if "一" <= ch <= "鿿":
                yield ch


lines = []
for ch in gb2312_hanzi():
    py = pinyin(ch, style=Style.TONE, heteronym=False)[0][0]
    if py and py != ch:
        lines.append(f"{ch}\t{py}")
OUT.write_text("# Generated by scripts/make-pinyin-table.py from pypinyin (MIT). Do not edit.\n"
               + "\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(lines)} hanzi -> {OUT}")
